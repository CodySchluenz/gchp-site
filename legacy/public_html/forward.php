<h3>Pay It Forward</h3><br><br>

For years the Grant County Holiday project, with community support, have been responsible for many kind acts, we are now requesting that all those wishing to receive Christmas gifts and/or toys from the Grant County Holiday Project will be a part of our year round giving by joining us in our "paying it forward" project.

<h4>How It Works</h4>

If you wish to receive benefits from the Holiday Project, you will need to give of yourself to others in your community. Giving does not mean money but providing random acts of kindness. These acts of kindness will be rewarded by the smiles and thanks you will receive.
When you request an application for the Holiday Project benefits, you will receive a form to list your good deeds and a place to name those who received your good deeds. You will return this form along with your Holiday Project application.

